#!/bin/bash
# Research experiments for spec 002 (plan phase). Usage: run.sh <label> <docker-config-dir or "">
# Every project, volume and network is named wtenv-research-*; the script removes them at the end.
set -u
LABEL="$1"
CFG="$2"
S="${RESEARCH_DIR:?set RESEARCH_DIR to a scratch directory holding fastapi-template/}"
W="$S/research/work-$LABEL"
rm -rf "$W"; mkdir -p "$W"
export DOCKER_HOST="unix://$HOME/.docker/run/docker.sock"
if [ -n "$CFG" ]; then export DOCKER_CONFIG="$CFG"; fi
unset COMPOSE_FILE COMPOSE_PROJECT_NAME COMPOSE_PATH_SEPARATOR COMPOSE_ENV_FILES COMPOSE_PROFILES

show() { # print the command, then run it and print its output and exit status
  echo
  echo "\$ $*"
  ( set -o pipefail; eval "$@" ) 2>&1
  echo "[exit $?]"
}
ports() { jq -c '[.services | to_entries[] | {s: .key, p: [.value.ports[]? | {target, published, host_ip, protocol}]}]'; }

echo "=== $LABEL: $(docker compose version)"

# ---------------------------------------------------------------- E1: ports across files
E1="$W/wtenv-research-e1"; mkdir -p "$E1/.wtenv"
cat > "$E1/compose.yaml" <<'EOF'
name: wtenv-research-e1-base
services:
  web:
    image: valkey/valkey:latest
    ports:
      - "18001:6379"
EOF
cat > "$E1/compose.override.yaml" <<'EOF'
services:
  web:
    command: ["valkey-server", "--port", "6379", "--save", ""]
    ports:
      - "127.0.0.1:18002:6379"
  api:
    image: valkey/valkey:latest
    ports:
      - "18003:6379"
EOF
cat > "$E1/.wtenv/plain.yaml" <<'EOF'
name: wtenv-research-e1-iso
services:
  "web":
    ports:
      - {"target": 6379, "published": "28001", "protocol": "tcp", "mode": "ingress"}
EOF
cat > "$E1/.wtenv/override.yaml" <<'EOF'
# Generated by wtenv for this worktree. Do not edit or commit; `wtenv up` rewrites it.
name: "wtenv-research-e1-iso"
services:
  "api":
    ports: !override
      - {"target": 6379, "published": "28003", "protocol": "tcp", "mode": "ingress"}
  "web":
    ports: !override
      - {"target": 6379, "published": "28001", "protocol": "tcp", "mode": "ingress"}
      - {"target": 6379, "published": "28002", "protocol": "tcp", "mode": "ingress", "host_ip": "127.0.0.1"}
EOF
cat > "$E1/.wtenv/reset.yaml" <<'EOF'
services:
  "web":
    ports: !reset []
EOF
echo; echo "## E1.1 compose.yaml + repository override, auto-loaded (no flags)"
show "cd $E1 && docker compose config --format json | ports"
echo; echo "## E1.2 + a third file with a plain ports: list"
show "cd $E1 && docker compose -f compose.yaml -f compose.override.yaml -f .wtenv/plain.yaml config --format json | ports"
echo; echo "## E1.3 + a third file with ports: !override (wtenv's generated layout)"
show "cd $E1 && docker compose -f compose.yaml -f compose.override.yaml -f .wtenv/override.yaml config --format json | jq -c '{name, ports: [.services | to_entries[] | {s: .key, p: [.value.ports[] | {target, published, host_ip}]}], web_command: .services.web.command}'"
echo; echo "## E1.4 + a third file with ports: !reset []"
show "cd $E1 && docker compose -f compose.yaml -f compose.override.yaml -f .wtenv/reset.yaml config --format json | ports"
echo; echo "## E1.4b the repository's override sets its own name: and a host port from a variable; the last file's name: wins"
{ printf 'name: wtenv-research-e1-repo\n'; sed 's/"127.0.0.1:18002:6379"/"127.0.0.1:${WEB_PORT:-18002}:6379"/' "$E1/compose.override.yaml"; } > "$E1/.wtenv/repo-named.yaml"
show "cd $E1 && docker compose -f compose.yaml -f .wtenv/repo-named.yaml config --format json | jq -c '{name, web: [.services.web.ports[] | .published]}'"
show "cd $E1 && WEB_PORT=18044 docker compose -f compose.yaml -f .wtenv/repo-named.yaml -f .wtenv/override.yaml config --format json | jq -c '{name, web: [.services.web.ports[] | .published]}'"
echo; echo "## E1.5 runtime: up -d with the three files, then the published ports of each container"
show "cd $E1 && docker compose -f compose.yaml -f compose.override.yaml -f .wtenv/override.yaml up -d --quiet-pull 2>&1 | tail -3"
show "docker ps --filter label=com.docker.compose.project=wtenv-research-e1-iso --format '{{.Names}} {{.Ports}}' | sort"
show "cd $E1 && docker compose -f compose.yaml -f compose.override.yaml -f .wtenv/override.yaml down --remove-orphans 2>&1 | tail -1"

# ---------------------------------------------------------------- E2: COMPOSE_FILE and the child's own flags
E2="$W/wtenv-research-e2"; mkdir -p "$E2/.wtenv" "$E2/backend" "$W/elsewhere"
cp "$E1/compose.yaml" "$E1/compose.override.yaml" "$E2/"
sed -i '' 's/wtenv-research-e1-base/wtenv-research-e2-base/' "$E2/compose.yaml"
sed 's/wtenv-research-e1-iso/wtenv-research-e2-iso/' "$E1/.wtenv/override.yaml" > "$E2/.wtenv/override.yaml"
printf 'SECRET=from-dot-env\n' > "$E2/.env"
cat >> "$E2/compose.override.yaml" <<'EOF'
    environment:
      FROM_DOT_ENV: ${SECRET:-unset}
EOF
CF="$E2/compose.yaml:$E2/compose.override.yaml:$E2/.wtenv/override.yaml"
summary="jq -c '{name, web: [.services.web.ports[] | .published], api: [.services.api.ports[] | .published], dotenv: .services.api.environment.FROM_DOT_ENV}'"
echo; echo "## E2.1 no flags, no COMPOSE_FILE (a plain command in the worktree: not isolated)"
show "cd $E2 && docker compose config --format json | $summary"
echo; echo "## E2.2 COMPOSE_FILE with three absolute paths, from the compose file's directory"
show "cd $E2 && COMPOSE_FILE=$CF docker compose config --format json | $summary"
echo; echo "## E2.3 the same from a subdirectory, and from a directory outside the project"
show "cd $E2/backend && COMPOSE_FILE=$CF docker compose config --format json | $summary"
show "cd $W/elsewhere && COMPOSE_FILE=$CF docker compose config --format json | $summary"
echo; echo "## E2.4 through a child shell (sh -c), as a script or make target would run it"
show "cd $E2 && COMPOSE_FILE=$CF sh -c 'sh -c \"docker compose config --format json\"' | $summary"
echo; echo "## E2.5 relative COMPOSE_FILE paths from a subdirectory"
show "cd $E2/backend && COMPOSE_FILE=compose.yaml:compose.override.yaml:.wtenv/override.yaml docker compose config --format json | $summary"
echo; echo "## E2.6 the child passes -p: its project name wins, the ports stay remapped"
show "cd $E2 && COMPOSE_FILE=$CF docker compose -p wtenv-research-e2-child config --format json | $summary"
echo; echo "## E2.7 the child passes -f: COMPOSE_FILE is ignored entirely"
show "cd $E2 && COMPOSE_FILE=$CF docker compose -f compose.yaml config --format json | jq -c '{name, web: [.services.web.ports[] | .published], services: (.services | keys)}'"
echo; echo "## E2.8 COMPOSE_PROJECT_NAME in the environment beside COMPOSE_FILE"
show "cd $E2 && COMPOSE_FILE=$CF COMPOSE_PROJECT_NAME=wtenv-research-e2-env docker compose config --format json | $summary"
echo; echo "## E2.9 COMPOSE_FILE in .env, and the environment's COMPOSE_FILE beside it"
cp "$E2/.env" "$E2/.env.bak"; printf 'COMPOSE_FILE=compose.yaml\n' >> "$E2/.env"
show "cd $E2 && docker compose config --format json | jq -c '{name, web: [.services.web.ports[] | .published], services: (.services | keys)}'"
show "cd $E2 && COMPOSE_FILE=$CF docker compose config --format json | $summary"
mv "$E2/.env.bak" "$E2/.env"
echo; echo "## E2.10 COMPOSE_PATH_SEPARATOR"
show "cd $E2 && COMPOSE_PATH_SEPARATOR=';' COMPOSE_FILE=$CF docker compose config --format json | $summary"
CFS="$E2/compose.yaml;$E2/compose.override.yaml;$E2/.wtenv/override.yaml"
show "cd $E2 && COMPOSE_PATH_SEPARATOR=';' COMPOSE_FILE='$CFS' docker compose config --format json | $summary"
show "cd $E2 && COMPOSE_PATH_SEPARATOR=':' COMPOSE_FILE=$CF docker compose config --format json | $summary"
echo; echo "## E2.11 --env-file and COMPOSE_ENV_FILES only feed interpolation; they cannot change ports or files"
printf 'SECRET=from-env-file\n' > "$E2/.wtenv/vars.env"
show "cd $E2 && docker compose --env-file .wtenv/vars.env config --format json | $summary"
show "cd $E2 && COMPOSE_ENV_FILES=.wtenv/vars.env docker compose config --format json | $summary"
echo; echo "## E2.12 a missing file in COMPOSE_FILE (isolation file deleted)"
show "cd $E2 && COMPOSE_FILE=$E2/compose.yaml:$E2/compose.override.yaml:$E2/.wtenv/missing.yaml docker compose config --format json | $summary"

# ---------------------------------------------------------------- E3: what config exposes
E3="$W/wtenv-research-e3"; mkdir -p "$E3"
cat > "$E3/.env" <<'EOF'
APP_PORT=18005
DB_PASSWORD=from-tracked-dot-env
VOL_SUFFIX=data
EOF
cat > "$E3/compose.yaml" <<'EOF'
services:
  app:
    image: valkey/valkey:latest
    ports:
      - "${APP_PORT}:6379"
      - "127.0.0.1::6380"
      - "6381"
      - "18010:53/udp"
    volumes:
      - app-${VOL_SUFFIX}:/data
      - ./cache:/cache
  db:
    image: postgres:17
    env_file: .env
    environment:
      POSTGRES_PASSWORD: ${DB_PASSWORD}
volumes:
  app-data:
EOF
cat > "$E3/compose.override.yaml" <<'EOF'
name: wtenv-research-e3-from-override
EOF
echo; echo "## E3.1 ports, volumes, name and environment after interpolation from the tracked .env"
show "cd $E3 && docker compose -f compose.yaml -f compose.override.yaml --profile '*' config --format json | jq -c '{name, ports: .services.app.ports, app_volumes: .services.app.volumes, volumes, db_env_keys: (.services.db.environment | keys), db_password: .services.db.environment.POSTGRES_PASSWORD, db_env_file: .services.db.env_file}'"
echo; echo "## E3.2 with no name: anywhere, config reports the default name"
show "cd $E3 && docker compose -f compose.yaml config --format json | jq -c '{name, volumes}'"
echo; echo "## E3.3 the environment beats .env in interpolation (what exec's variables do to Compose)"
show "cd $E3 && APP_PORT=18099 docker compose -f compose.yaml config --format json | jq -c '[.services.app.ports[0].published]'"
echo; echo "## E3.4 docker compose config --environment (the interpolation values)"
show "cd $E3 && docker compose -f compose.yaml config --environment 2>&1 | grep -E '^(APP_PORT|DB_PASSWORD|VOL_SUFFIX)=|unknown flag' | sed 's/=.*/=<value>/'"

# ---------------------------------------------------------------- E4: where a database keeps its data
E4="$W/wtenv-research-e4"; mkdir -p "$E4/data" "$W/outside-data"
docker volume create wtenv-research-e4-external >/dev/null
cat > "$E4/compose.yaml" <<EOF
name: wtenv-research-e4
services:
  db_anon_declared:
    image: postgres:17
    volumes:
      - /var/lib/postgresql/data
  db_none:
    image: postgres:17
  db_project:
    image: postgres:17
    volumes:
      - pgdata:/var/lib/postgresql/data
  db_fixed:
    image: postgres:17
    volumes:
      - fixed:/var/lib/postgresql/data
  db_external:
    image: postgres:17
    volumes:
      - external:/var/lib/postgresql/data
  db_bind_inside:
    image: postgres:17
    volumes:
      - ./data:/var/lib/postgresql/data
  db_bind_outside:
    image: postgres:17
    volumes:
      - $W/outside-data:/var/lib/postgresql/data
      - /etc/localtime:/etc/localtime:ro
  db_device:
    image: postgres:17
    volumes:
      - device:/var/lib/postgresql/data
  db_tmpfs:
    image: postgres:17
    tmpfs:
      - /var/lib/postgresql/data
volumes:
  pgdata:
  fixed:
    name: wtenv-research-e4-shared
  external:
    name: wtenv-research-e4-external
    external: true
  device:
    driver_opts:
      type: none
      o: bind
      device: $W/outside-data
EOF
echo; echo "## E4.1 the resolved mounts of each database service, and the top-level volumes"
show "cd $E4 && docker compose config --format json | jq -c '.services | to_entries[] | {s: .key, volumes: .value.volumes, tmpfs: .value.tmpfs}'"
show "cd $E4 && docker compose config --format json | jq -c '{name, volumes}'"
echo; echo "## E4.2 the image's own VOLUME (not in the compose model)"
show "docker image inspect postgres:17 --format '{{json .Config.Volumes}} {{range .Config.Env}}{{if eq (index (split . \"=\") 0) \"PGDATA\"}}{{.}}{{end}}{{end}}'"
echo; echo "## E4.3 runtime: db_none gets an anonymous, unlabelled volume from the image"
show "cd $E4 && POSTGRES_PASSWORD=x docker compose run -d --name wtenv-research-e4-none -e POSTGRES_PASSWORD=x db_none >/dev/null; sleep 2; docker container inspect wtenv-research-e4-none --format '{{range .Mounts}}{{.Type}} name-length={{len .Name}} dest={{.Destination}}{{end}}'"
show "docker volume ls --filter label=com.docker.compose.project=wtenv-research-e4 --format '{{.Name}}'; echo '(the labelled volumes: compose run created every declared volume; the anonymous one is not among them)'"
show "docker rm -f -v wtenv-research-e4-none >/dev/null && echo removed with its anonymous volume"
echo; echo "## E4.4 cleanup of the project's network and the external volume"
show "cd $E4 && docker compose down --remove-orphans 2>&1 | tail -1"
show "docker volume rm wtenv-research-e4_pgdata wtenv-research-e4-shared wtenv-research-e4_device wtenv-research-e4-external"


# ---------------------------------------------------------------- E5: the fastapi template's published ports
echo; echo "## E5.1 the fastapi template, compose.yml + compose.override.yml, every profile"
show "cd $S/fastapi-template && docker compose -f compose.yml -f compose.override.yml --profile '*' config --format json | jq -c '[.services | to_entries[] | select(.value.ports) | {s: .key, p: [.value.ports[] | {target, protocol, published}]}]'"
show "cd $S/fastapi-template && docker compose -f compose.yml -f compose.override.yml --profile '*' config --format json | jq -c '{name, db_volumes: .services.db.volumes, volumes, db_env_keys: (.services.db.environment | keys)}'"
echo; echo "=== $LABEL done"
