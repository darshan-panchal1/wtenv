"""What wtenv writes for the isolation of a worktree, and what `exec` checks before applying it.

Shared by `compose`, `provision` and `execcmd`. `exec` must not import `wtenv.compose` (NFR-001),
so everything its checks need lives here: wtenv's header line, the isolation path, the four
override names, and the `.env` line rule. This module imports only `errors`, `identity` and
`registry`, never `compose`, `provision` or `database`.
"""

import os
import posixpath
import re
from collections.abc import Mapping
from pathlib import Path

from wtenv.errors import ErrorCode, JsonValue, WtenvError
from wtenv.identity import recorded_path_problem, symlinked_part
from wtenv.registry import ComposeRecord

# The first line of every file wtenv generates for Compose: the auto-loaded override and the
# isolation file. A file that does not start with it is not wtenv's (001:FR-087).
OVERRIDE_HEADER = (
    "# Generated by wtenv for this worktree. Do not edit or commit; `wtenv up` rewrites it.\n"
)

# Where wtenv writes its isolation settings when the repository owns its override file
# (FR-009), relative to the worktree root. Compose never loads it on its own.
ISOLATION_FILE = ".wtenv/compose.isolation.yaml"

# The names Compose loads beside the compose file without being asked; the pairs follow
# `config.COMPOSE_FILE_NAMES` (a unit test checks it).
OVERRIDE_FILE_NAMES = (
    "compose.override.yaml",
    "compose.override.yml",
    "docker-compose.override.yaml",
    "docker-compose.override.yml",
)

# Both outrank the override file, so a worktree that sets one is not isolated (FR-033, check 1).
COMPOSE_OVERRIDE_VARIABLES = ("COMPOSE_PROJECT_NAME", "COMPOSE_FILE")
# `exec` also refuses a non-empty `COMPOSE_ENV_FILES` in its own environment, because a file
# listed there can set the project name (research R7, E6.3d); `.env` cannot set it.
EXEC_REFUSED_VARIABLES = (*COMPOSE_OVERRIDE_VARIABLES, "COMPOSE_ENV_FILES")
# One `.env` assignment, as `compose.check_environment` and `exec` check 1 both read it. It is the
# form Compose honours (research R7, E6.1): `=` or `:` after the name, an optional leading
# byte-order mark, and `export`.
ENV_ASSIGNMENT = re.compile(r"\ufeff?\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*[=:]\s*(.*)")


def compose_environment(root: Path, record: ComposeRecord) -> dict[str, str]:
    """Return the environment that makes Compose load the isolation file (data-model.md).

    `COMPOSE_FILE` names, as absolute paths under `root`, the compose file, the repository's
    override and the isolation file, in that order, and `COMPOSE_PATH_SEPARATOR` is `:`.
    `COMPOSE_ENV_FILES` is the `.env` beside the compose file when it exists, else `/dev/null`.
    `COMPOSE_PROJECT_NAME` is never set: the project name comes from the isolation file (R2).
    `record` is the entry's compose record in the exec-only arrangement; raises `ValueError`
    for a record without a repository override, which has nothing to isolate this way.
    """
    if record.repository_override is None:
        raise ValueError("the compose record has no repository override")
    files = [record.file, record.repository_override, ISOLATION_FILE]
    dot_env = root / posixpath.dirname(record.file) / ".env"
    return {
        "COMPOSE_FILE": ":".join(str(root / name) for name in files),
        "COMPOSE_PATH_SEPARATOR": ":",
        # Compose then reads this `.env`, or none, and no other from any directory, so a `.env`
        # in the current directory cannot set the project name (research R7, E6.3b, E6.3c).
        "COMPOSE_ENV_FILES": str(dot_env) if os.path.isfile(dot_env) else "/dev/null",
    }


def check_isolation(root: Path, record: ComposeRecord, environ: Mapping[str, str]) -> None:
    """Raise `isolation_unavailable` unless `exec` can apply the isolation settings (FR-033).

    Runs the seven checks of data-model.md, "`exec` checks (FR-033)", in order, for an entry that
    records `repository_override`; the first failure is raised and nothing is written. `root` is
    the recorded worktree path and `environ` the calling environment.
    """
    assert record.repository_override is not None
    _check_variables(root, record.file, environ)  # 1
    _check_recorded_values(root, record)  # 2
    isolation_file = root / ISOLATION_FILE
    link = symlinked_part(root, ISOLATION_FILE)  # 3
    if link is not None:
        raise _unavailable("symlink", f"{link} is a symbolic link", link)
    if not os.path.lexists(isolation_file):  # 4
        raise _unavailable(
            "isolation_file_missing", f"{isolation_file} does not exist", isolation_file
        )
    if not _starts_with_header(isolation_file):  # 5
        raise _unavailable(
            "isolation_file_not_wtenvs",
            f"{isolation_file} does not start with wtenv's header line, so it is not wtenv's",
            isolation_file,
        )
    repository_override = root / record.repository_override
    if not os.path.lexists(repository_override):  # 6
        raise _unavailable(
            "repository_override_missing",
            f"{repository_override} does not exist",
            repository_override,
        )
    directory = posixpath.dirname(record.file)  # 7
    for name in OVERRIDE_FILE_NAMES:
        relative = posixpath.join(directory, name)
        if relative != record.repository_override and os.path.lexists(root / relative):
            raise _unavailable(
                "override_appeared",
                f"{root / relative} appeared beside the compose file, and Compose would load it",
                root / relative,
            )


def _check_variables(root: Path, compose_file: str, environ: Mapping[str, str]) -> None:
    """Check 1: `COMPOSE_PROJECT_NAME` and `COMPOSE_FILE` are not set, in `environ` or `.env`,
    and `COMPOSE_ENV_FILES` is not set in `environ`.

    An empty value does not count, because Compose ignores it. `.env` is the one beside the
    compose file, and `details.path` names it when the value comes from there. The values are
    never printed.
    """
    for variable in EXEC_REFUSED_VARIABLES:
        if environ.get(variable):
            raise _unavailable(
                "compose_env_override",
                f"{variable} is set in the environment, so Compose would not use the isolation "
                "file",
                None,
                variable=variable,
            )
    dot_env = root / posixpath.dirname(compose_file) / ".env"
    try:
        text = dot_env.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return
    for line in text.splitlines():
        match = ENV_ASSIGNMENT.fullmatch(line)
        if (
            match is not None
            and match.group(1) in COMPOSE_OVERRIDE_VARIABLES
            and match.group(2).strip()
        ):
            raise _unavailable(
                "compose_env_override",
                f"{match.group(1)} is set in {dot_env}, so Compose would not use the isolation file",
                dot_env,
                variable=match.group(1),
            )


def _check_recorded_values(root: Path, record: ComposeRecord) -> None:
    """Check 2: the recorded values have the form `up` records (the registry can be edited)."""
    if record.override != ISOLATION_FILE:
        raise _unavailable(
            "recorded_value_invalid",
            f"the registry records {record.override!r} as the override, not {ISOLATION_FILE}",
            root / record.override,
        )
    assert record.repository_override is not None
    for value in (record.repository_override, record.file):
        problem = recorded_path_problem(value)
        if problem is not None:
            raise _unavailable(
                "recorded_value_invalid",
                f"the registry records {value!r}, which is {problem}",
                root / value,
            )
    # `up` records the repository's override beside the compose file under one of the four names
    # (L4); a hand-edited registry must not make `exec` load any other file.
    override = record.repository_override
    if (
        posixpath.dirname(override) != posixpath.dirname(record.file)
        or posixpath.basename(override) not in OVERRIDE_FILE_NAMES
    ):
        raise _unavailable(
            "recorded_value_invalid",
            f"the registry records {override!r} as the repository's override, which is not one "
            "of the four override names beside the compose file",
            root / override,
        )


def _starts_with_header(path: Path) -> bool:
    """Return whether the file at `path` starts with wtenv's header line; unreadable is False."""
    try:
        with open(path, "rb") as file:
            first_line = file.readline(len(OVERRIDE_HEADER) + 1)
    except OSError:
        return False
    return first_line == OVERRIDE_HEADER.encode("utf-8")


def _unavailable(
    reason: str, why: str, path: Path | None, *, variable: str | None = None
) -> WtenvError:
    """Build `isolation_unavailable`: `exec` cannot apply the isolation settings (FR-033)."""
    details: dict[str, JsonValue] = {"reason": reason}
    if variable is not None:
        details["variable"] = variable
    if path is not None:
        details["path"] = str(path)
    return WtenvError(
        ErrorCode.ISOLATION_UNAVAILABLE,
        f"{why}; the command was not run",
        hint="Fix that, or run `wtenv up` in this worktree, then run the command again.",
        details=details,
    )


def check_inherited_compose_file(root: Path, environ: Mapping[str, str]) -> None:
    """Check A: raise `isolation_unavailable` when `COMPOSE_FILE` names another worktree's file.

    Applies to every provisioned worktree that is not exec-only, and to `up` before its post-up
    commands (FR-033, safety finding M1). `COMPOSE_FILE` is split on `COMPOSE_PATH_SEPARATOR`
    (default `:`). An entry that ends in `/.wtenv/compose.isolation.yaml` and is not this
    worktree's own isolation file is refused. Any other value is passed through, as in v0.1.1.
    `details.path` is the other worktree's isolation file, as an absolute path.
    """
    value = environ.get("COMPOSE_FILE")
    if not value:
        return
    separator = environ.get("COMPOSE_PATH_SEPARATOR") or ":"
    own = os.path.normpath(root / ISOLATION_FILE)
    for entry in value.split(separator):
        other = os.path.abspath(entry)
        if entry.endswith(f"/{ISOLATION_FILE}") and other != own:
            raise _unavailable(
                "compose_env_override",
                f"COMPOSE_FILE names {other}, the isolation file of another worktree, so Compose "
                "would run this worktree with that worktree's settings",
                Path(other),
                variable="COMPOSE_FILE",
            )


def check_automatic_override(root: Path, record: ComposeRecord) -> None:
    """Check B: raise `isolation_unavailable` when an override appeared in the automatic arrangement.

    Applies to a compose record without `repository_override` whose `override` is an auto-loaded
    override name and whose state is `created` (FR-033, safety finding M5). Compose prefers
    `compose.override.yml` over `compose.override.yaml` and only warns, so wtenv's file would
    silently not apply. Refused: another override name beside the compose file; the recorded
    override replaced by a symbolic link (nothing is read through it) or by a file without
    wtenv's header. A missing recorded override passes, as in v0.1.1. For any other record the
    function does nothing: a record that is `removing` means `[compose]` was removed, wtenv's file
    is gone, and the override files that remain are the developer's own.
    """
    if (
        record.repository_override is not None
        or record.override_state.value != "created"
        or posixpath.basename(record.override) not in OVERRIDE_FILE_NAMES
    ):
        return
    directory = posixpath.dirname(record.file)
    for name in OVERRIDE_FILE_NAMES:
        relative = posixpath.join(directory, name)
        if relative != record.override and os.path.lexists(root / relative):
            raise _unavailable(
                "override_appeared",
                f"{root / relative} appeared beside the compose file; Compose would prefer it "
                "to wtenv's override, which would then silently not apply",
                root / relative,
            )
    recorded = root / record.override
    if os.path.islink(recorded):  # the link is refused before any read
        raise _unavailable("symlink", f"{recorded} is a symbolic link", recorded)
    if os.path.lexists(recorded) and not _starts_with_header(recorded):
        raise _unavailable(
            "override_appeared",
            f"{recorded} no longer starts with wtenv's header line, so it is not wtenv's override",
            recorded,
        )
