"""A hand-edited registry must not make `down` or `gc` touch anything wtenv did not create
(T176 to T178, T211; FR-039, FR-044, FR-086; review 2, findings H1 and H2).

The registry is a file a person can edit. Each test provisions a worktree with `up`, edits one
recorded field in `registry.json` to point at a decoy that the test made outside wtenv, and runs
`down --dry-run`, `down`, `gc` (after `git worktree remove`), and `gc --release` (after the
repository is deleted). In every run the decoy is as it was: the same bytes, the same containers,
the same database. A value of a form wtenv never records is reported under `failed`, its record
stays, the entry stays, and the exit status is 13 (0 for a dry run).

Nothing here touches anything outside its own temporary repository and its own temporary state
directory. The Docker decoys are made by the test, under unique names, and removed by exactly those
names at the end of the test; `postgres-local` and every other container are never looked at.
"""

