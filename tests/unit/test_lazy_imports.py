def test_exec_does_not_load_the_compose_module(make_repo: object, tmp_path: Path) -> None:
    """NFR-001: `exec` runs the isolation checks without importing `wtenv.compose`.

    A throwaway repository gets a compose record of the exec-only arrangement and the files its
    checks look at; no Docker is involved. The child process reads the environment `exec` would
    give the command, and reports whether the compose module was loaded.
    """
    repo = make_repo("app")  # type: ignore[operator]
    env = {**os.environ, "XDG_STATE_HOME": str(tmp_path / "state")}
    run = lambda *args: subprocess.run(
        [sys.executable, "-m", "wtenv", *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=True,
    )
    run("up")
    (repo / ".wtenv").mkdir()
    (repo / "compose.yaml").write_text("services: {}\n")
    (repo / "compose.override.yml").write_text("services: {}\n")
    (repo / ".wtenv" / "compose.isolation.yaml").write_text(
        "# Generated by wtenv for this worktree. Do not edit or commit; `wtenv up` rewrites it.\n"
    )
    script = (
        "import json, sys\n"
        "from wtenv import registry\n"
        "from wtenv.identity import current_worktree\n"
        "with registry.transaction() as reg:\n"
        "    entry = reg.worktrees[current_worktree().git_dir]\n"
        "    entry.compose = registry.ComposeRecord(project='wtenv-app-00000000',\n"
        "        file='compose.yaml', override='.wtenv/compose.isolation.yaml',\n"
        "        override_state='created', repository_override='compose.override.yml')\n"
        "from wtenv.execcmd import command_environment\n"
        "environment = command_environment()\n"
        "print(json.dumps({'compose_file': 'COMPOSE_FILE' in environment,\n"
        "    'loaded': 'wtenv.compose' in sys.modules}))\n"
    )

    result = subprocess.run(
        [sys.executable, "-c", script],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        check=True,
    )

    # The exec-only checks ran (the environment has the isolation variables) and imported nothing.
    assert json.loads(result.stdout) == {"compose_file": True, "loaded": False}
