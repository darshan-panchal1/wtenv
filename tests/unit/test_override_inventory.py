def test_one_repository_file_and_wtenvs_own_file_marks_wtenvs_for_removal(
    make_repo: Callable[[str], Path],
) -> None:
    repo = make_repo("one-plus-own")
    (repo / RECORDED).write_text(WTENVS)
    (repo / OTHER).write_text(DEVELOPERS)

    inventory = compose.override_inventory(repo, "compose.yaml", RECORDED)

    assert kinds(inventory) == {RECORDED: "wtenv_own", OTHER: "repository_owned"}
    assert inventory.arrangement == "exec_only"
    assert inventory.repository_override == OTHER
    assert inventory.remove == (RECORDED,)
    assert (repo / RECORDED).read_text() == WTENVS  # marked, never removed by the inventory
    assert (repo / OTHER).read_text() == DEVELOPERS


def test_one_adopted_file_and_one_repository_file_are_two_repository_files(
    make_repo: Callable[[str], Path],
) -> None:
    repo = make_repo("adopt-plus-one")
    (repo / RECORDED).write_text(DEVELOPERS)
    track(repo, RECORDED)
    (repo / OTHER).write_text(DEVELOPERS)

    with pytest.raises(WtenvError) as caught:
        compose.override_inventory(repo, "compose.yaml", RECORDED)

    assert caught.value.code is ErrorCode.OVERRIDE_AMBIGUOUS


@pytest.mark.parametrize(
    "names",
    [
        ("compose.override.yml", "compose.override.yaml"),
        ("docker-compose.override.yml", "compose.override.yml"),
        ("docker-compose.override.yaml", "compose.override.yaml", "compose.override.yml"),
    ],
    ids=["two", "two, one per family", "three"],
)
def test_two_or_more_repository_files_are_override_ambiguous_and_nothing_changes(
    tmp_path: Path, names: tuple[str, ...]
) -> None:
    for name in names:
        (tmp_path / name).write_text(DEVELOPERS + f"# {name}\n")
    before = snapshot(tmp_path)

    with pytest.raises(WtenvError) as caught:
        compose.override_inventory(tmp_path, "compose.yaml", None)

    error = caught.value
    assert error.code is ErrorCode.OVERRIDE_AMBIGUOUS
    assert EXIT_STATUS[error.code] == 21
    assert error.details["files"] == sorted(str(tmp_path / name) for name in names)
    assert all(os.path.isabs(str(path)) for path in error.details["files"])  # type: ignore[union-attr]
    assert snapshot(tmp_path) == before


def test_two_repository_files_beside_a_nested_compose_file_are_named_with_their_directory(
    tmp_path: Path,
) -> None:
    (tmp_path / "deploy").mkdir()
    for name in ("compose.override.yml", "compose.override.yaml"):
        (tmp_path / "deploy" / name).write_text(DEVELOPERS)

    with pytest.raises(WtenvError) as caught:
        compose.override_inventory(tmp_path, "deploy/compose.yaml", None)

    assert caught.value.details["files"] == [
        str(tmp_path / "deploy" / "compose.override.yaml"),
        str(tmp_path / "deploy" / "compose.override.yml"),
    ]


def test_the_inventory_is_read_only(make_repo: Callable[[str], Path]) -> None:
    repo = make_repo("read-only")
    (repo / RECORDED).write_text(WTENVS)
    (repo / OTHER).write_text(DEVELOPERS)
    (repo / OTHER).chmod(0o640)
    before = snapshot(repo)

    compose.override_inventory(repo, "compose.yaml", RECORDED)

    assert snapshot(repo) == before


