"""The override inventory of `up` step 5 (FR-001, FR-006, FR-007; data-model.md, "Override inventory").

The inventory classifies the override files beside the compose file and chooses the arrangement.
It is read only. A file git must track is made with a real `git init` and commit, in a throwaway
repository under `tmp_path`.
"""

import os
import subprocess
from collections.abc import Callable
from pathlib import Path

import pytest

from wtenv import compose
from wtenv.errors import EXIT_STATUS, ErrorCode, WtenvError

HEADER = "# Generated by wtenv for this worktree. Do not edit or commit; `wtenv up` rewrites it.\n"
WTENVS = HEADER + 'name: "wtenv-app-0123abcd"\n'  # a file wtenv wrote
DEVELOPERS = "services:\n  web:\n    command: serve\n"  # a file the repository owns

RECORDED = "compose.override.yaml"
OTHER = "compose.override.yml"


def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True, text=True)


def track(repo: Path, *relative: str) -> None:
    """Make git track the files `relative` (paths under `repo`) with a real commit."""
    _git(repo, "add", "--force", "--", *relative)
    _git(repo, "commit", "-m", "track the override")


def snapshot(root: Path) -> dict[str, tuple[str, bytes | str | None, int]]:
    """Describe everything under `root` without following a link: kind, content, mode."""
    described: dict[str, tuple[str, bytes | str | None, int]] = {}
    for path in [root, *sorted(root.rglob("*"))]:
        if ".git" in path.relative_to(root).parts:
            continue
        mode = path.lstat().st_mode
        relative = str(path.relative_to(root))
        if path.is_symlink():
            described[relative] = ("link", os.readlink(path), mode)
        elif path.is_dir():
            described[relative] = ("dir", None, mode)
        else:
            described[relative] = ("file", path.read_bytes(), mode)
    return described


def kinds(inventory: compose.OverrideInventory) -> dict[str, str]:
    """Return `{path: class}` of every file in the inventory."""
    return {file.path: file.kind for file in inventory.files}


