"""`down` and `gc` use a recorded path only when it has the form wtenv records (T181, T183;
FR-039, FR-086; cli.md, `wtenv down`, "Recorded values").

The registry is a file a person can edit. A recorded env file, SQLite copy, or override that is
absolute, climbs out with `..`, or that normalisation would change is a `failed` item: nothing is
unlinked or rewritten, the record stays untouched, and the entry stays. Each case writes a decoy
where the value would lead, and checks it byte for byte. No Docker is needed: the compose project
is of the right form, and the removal of its resources is replaced by a function that finds none.
"""

import os
import subprocess
from pathlib import Path

import pytest

from wtenv import compose, registry, teardown
from wtenv.database import Removal
from wtenv.identity import recorded_path_problem
from wtenv.output import ItemKind, ResourceState
from wtenv.registry import (
    ComposeRecord,
    DatabaseRecord,
    EnvFileRecord,
    PortBlock,
    WorktreeEntry,
)

GIT_DIR = "/repos/app/.git/worktrees/app"
BEGIN = "# >>> wtenv managed (rewritten by `wtenv up`; do not edit) >>>"
END = "# <<< wtenv managed <<<"
SECTION = f"A=1\n{BEGIN}\nPORT=1\n{END}\n".encode()
HEADER = "# Generated by wtenv for this worktree. Do not edit or commit; `wtenv up` rewrites it.\n"
OWN_OVERRIDE = (HEADER + 'name: "x"\n').encode()


@pytest.fixture(autouse=True)
def no_docker(monkeypatch: pytest.MonkeyPatch) -> None:
    """The recorded project has no resources; no `docker` command is ever run."""

    def nothing_found(project: str, git_dir: str, **kwargs: object) -> Removal:
        return Removal()

    monkeypatch.setattr(compose, "remove_project", nothing_found)


