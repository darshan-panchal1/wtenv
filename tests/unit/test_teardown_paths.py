@pytest.fixture
def root(tmp_path: Path) -> Path:
    path = tmp_path / "work" / "feature-x"
    path.mkdir(parents=True)
    return path


def entry_at(root: Path, **records: object) -> WorktreeEntry:
    return WorktreeEntry(
        git_dir=GIT_DIR,
        path=str(root),
        repository="/repos/app/.git",
        state="provisioned",
        block=PortBlock(start=20000, size=10),
        **records,  # type: ignore[arg-type]
    )


def env_record(path: str) -> EnvFileRecord:
    return EnvFileRecord(
        path=path, created_file=True, added_newline=False, state=ResourceState.CREATED
    )


def sqlite_record(path: str) -> DatabaseRecord:
    return DatabaseRecord(kind="sqlite", path=path, state=ResourceState.CREATED)


def compose_record(override: str) -> ComposeRecord:
    return ComposeRecord(
        project=compose.project_name("app", GIT_DIR),
        file="compose.yaml",
        override=override,
        override_state=ResourceState.CREATED,
    )


def record(entry: WorktreeEntry) -> None:
    with registry.transaction() as reg:
        reg.worktrees[entry.git_dir] = entry


def where_it_leads(root: Path, value: str) -> Path:
    """The file a value would lead to if it were used without a check."""
    return Path(os.path.normpath(os.path.join(root, value)))


# The value for a path under `root`, `outside` being a directory beside it, and the word the reason
# names the rule with.
BAD_VALUES = {
    "absolute": (lambda root: str(root.parent / "elsewhere" / "f"), "absolute"),
    "parent": (lambda root: "../f", "`..`"),
    "inside parent": (lambda root: "a/../f", "`..`"),
    "dot": (lambda root: "./f", "plain"),
    "double slash": (lambda root: "a//f", "plain"),
}


def put(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)


@pytest.mark.parametrize("dry_run", [True, False])
@pytest.mark.parametrize("name", BAD_VALUES)
def test_a_recorded_env_file_of_a_form_wtenv_never_records_is_left_alone(
    name: str, dry_run: bool, root: Path
) -> None:
    value, word = BAD_VALUES[name][0](root), BAD_VALUES[name][1]
    decoy = where_it_leads(root, value)
    put(decoy, SECTION)
    original = env_record(value)
    entry = entry_at(root, env_file=original)
    record(entry)

    release = teardown.plan_release(entry) if dry_run else teardown.release_entry(entry)

    assert decoy.read_bytes() == SECTION
    assert [(f.kind, f.name) for f in release.failed] == [(ItemKind.ENV_SECTION, str(root / value))]
    assert word in release.failed[0].reason
    assert release.removed == [] and release.released is False
    assert registry.load().worktrees[GIT_DIR].env_file == original  # untouched, state included


@pytest.mark.parametrize("dry_run", [True, False])
@pytest.mark.parametrize("name", BAD_VALUES)
def test_a_recorded_sqlite_path_of_a_form_wtenv_never_records_is_left_alone(
    name: str, dry_run: bool, root: Path
) -> None:
    value, word = BAD_VALUES[name][0](root), BAD_VALUES[name][1]
    decoy = where_it_leads(root, value)
    sides = [Path(f"{decoy}{suffix}") for suffix in ("", "-wal", "-shm", "-journal")]
    for path in sides:
        put(path, f"mine: {path.name}".encode())
    original = sqlite_record(value)
    entry = entry_at(root, databases=[original])
    record(entry)

    release = teardown.plan_release(entry) if dry_run else teardown.release_entry(entry)

    assert [path.read_bytes() for path in sides] == [f"mine: {p.name}".encode() for p in sides]
    assert [(f.kind, f.name) for f in release.failed] == [(ItemKind.SQLITE_FILE, str(root / value))]
    assert word in release.failed[0].reason
    assert release.removed == [] and release.already_absent == []  # no side file is even listed
    assert registry.load().worktrees[GIT_DIR].databases == [original]


